type AnyContent = proto.IMessage | null | undefined;

/** The poll creation of a message: V1/V2/V3/V5, V4 (future-proof wrapper), inside ephemeral/view-once. */
export function pollCreationOf(
  message: AnyContent
): proto.Message.IPollCreationMessage | undefined {
  const content = normalizeMessageContent(message as WAMessageContent | undefined);
  if (!content) return undefined;
  const direct =
    content.pollCreationMessage ||
    content.pollCreationMessageV2 ||
    content.pollCreationMessageV3 ||
    content.pollCreationMessageV5;
  if (direct) return direct;
  const inner = content.pollCreationMessageV4?.message;
  return inner && inner !== message ? pollCreationOf(inner) : undefined;
}

/** Question, options and selectable count of a poll message; null when it is not one. */
export function parsePollDefinition(message: AnyContent): PollDefinition | null {
  const creation = pollCreationOf(message);
  if (!creation) return null;
  const options = (creation.options || [])
    .map(option => (typeof option?.optionName === 'string' ? option.optionName : ''))
    .filter(name => name.length > 0);
  if (!options.length) return null;
  const raw = Number(creation.selectableOptionsCount ?? 0);
  const selectableCount =
    Number.isFinite(raw) && raw >= 1 ? Math.min(Math.floor(raw), options.length) : 0;
  return { question: String(creation.name || ''), options, selectableCount };
}

function bytes(value: unknown): Uint8Array | null {
  if (value instanceof Uint8Array) return value;
  if (typeof value === 'string' && value) return new Uint8Array(Buffer.from(value, 'base64'));
  if (Array.isArray(value) && value.every(n => typeof n === 'number')) return new Uint8Array(value);
  const tagged = value as { type?: unknown; data?: unknown } | null;
  if (tagged && tagged.type === 'Buffer' && Array.isArray(tagged.data)) {
    return new Uint8Array(tagged.data as number[]);
  }
  return null;
}

/**
 * The 32-byte messageSecret of a poll/event creation message (the encKey of
 * its votes / responses): top level or inside a wrapper. null when absent —
 * the message was stored without it (before PR-1) or WhatsApp never sent it.
 */
export function messageSecretOf(message: AnyContent): Uint8Array | null {
  const candidates = [
    (message as proto.IMessage | undefined)?.messageContextInfo?.messageSecret,
    normalizeMessageContent(message as WAMessageContent | undefined)?.messageContextInfo
      ?.messageSecret,
  ];
  for (const candidate of candidates) {
    const secret = bytes(candidate);
    if (secret && secret.length === 32) return secret;
  }
  return null;
}

/** Hex SHA-256 of an option name — what a vote carries for each selected option. */
export function optionHash(name: string): string {
  return Buffer.from(sha256(Buffer.from(name))).toString('hex');
}

/** Selected hashes → option names of the poll; hashes of no known option are kept apart. */
export function selectedOptionNames(
  definition: PollDefinition | null,
  hashes: string[]
): { names: string[]; unknown: string[] } {
  const byHash = new Map((definition?.options || []).map(name => [optionHash(name), name]));
  const names: string[] = [];
  const unknown: string[] = [];
  for (const hash of hashes) {
    const name = byHash.get(hash);
    if (name !== undefined) {
      if (!names.includes(name)) names.push(name);
    } else unknown.push(hash);
  }
  return { names, unknown };
}

