/**
 * A poll to send: the limits of the official client, trimmed. An empty or
 * repeated option is refused rather than dropped (voters would otherwise see
 * a list that is not the one written). selectableCount: 0 (default) = any
 * number, 1 = single choice, up to the number of options.
 */
export function validatePollInput(input: {
  name: unknown;
  options: unknown;
  selectableCount?: unknown;
}): ValidatedPoll {
  const name = typeof input.name === 'string' ? input.name.trim() : '';
  if (!name) throw new PollEventInputError('A poll needs a question (name)', { field: 'name' });
  if (name.length > POLL_QUESTION_MAX_LENGTH) {
    throw new PollEventInputError(
      `The question is longer than ${POLL_QUESTION_MAX_LENGTH} characters`,
      { field: 'name', maxLength: POLL_QUESTION_MAX_LENGTH }
    );
  }
  if (!Array.isArray(input.options)) {
    throw new PollEventInputError('options must be a list of option names', { field: 'options' });
  }
  if (input.options.length < POLL_MIN_OPTIONS || input.options.length > POLL_MAX_OPTIONS) {
    throw new PollEventInputError(
      `A poll needs between ${POLL_MIN_OPTIONS} and ${POLL_MAX_OPTIONS} options`,
      {
        field: 'options',
        min: POLL_MIN_OPTIONS,
        max: POLL_MAX_OPTIONS,
        given: input.options.length,
      }
    );
  }
  const options = input.options.map((value: unknown, index: number) => {
    const option = typeof value === 'string' ? value.trim() : '';
    if (!option) {
      throw new PollEventInputError(`Option ${index + 1} is empty or not text`, {
        field: 'options',
        index,
      });
    }
    if (option.length > POLL_OPTION_MAX_LENGTH) {
      throw new PollEventInputError(
        `Option ${index + 1} is longer than ${POLL_OPTION_MAX_LENGTH} characters`,
        { field: 'options', index, maxLength: POLL_OPTION_MAX_LENGTH }
      );
    }
    return option;
  });
  if (new Set(options).size !== options.length) {
    throw new PollEventInputError('Poll options cannot repeat', { field: 'options' });
  }
  const raw = input.selectableCount;
  const selectableCount = raw === undefined || raw === null ? 0 : Number(raw);
  if (
    !Number.isInteger(selectableCount) ||
    selectableCount < 0 ||
    selectableCount > options.length
  ) {
    throw new PollEventInputError(
      `selectableCount must be an integer from 0 (any) to ${options.length}`,
      { field: 'selectableCount', max: options.length }
    );
  }
  return { name, options, selectableCount };
}

/** Baileys content of a validated poll (it adds the messageSecret itself). */
export function buildPollContent(poll: ValidatedPoll): AnyMessageContent {
  return {
    poll: { name: poll.name, values: poll.options, selectableCount: poll.selectableCount },
  } as AnyMessageContent;
}

/**
 * The options of a vote: exact names of the poll (never trimmed — WhatsApp
 * hashes the exact string), no repeats, at most selectableCount; [] retracts.
 */
export function validatePollSelection(definition: PollDefinition, requested: unknown): string[] {
  const refuse = (message: string, extra: Record<string, unknown> = {}): never => {
    throw new PollEventInputError(message, { validOptions: definition.options, ...extra });
  };
  if (!Array.isArray(requested)) refuse('options must be a list of option names ([] retracts)');
  const names = requested as unknown[];
  if (names.some(name => typeof name !== 'string' || !name)) {
    refuse('options must be non-empty strings');
  }
  const exact = names as string[];
  if (new Set(exact).size !== exact.length) refuse('options must not repeat an option');
  const unknown = exact.filter(name => !definition.options.includes(name));
  if (unknown.length) refuse(`Unknown poll option: ${JSON.stringify(unknown[0])}`, { unknown });
  const max =
    definition.selectableCount >= 1 ? definition.selectableCount : definition.options.length;
  if (exact.length > max)
    refuse(`This poll allows at most ${max} option(s)`, { maxSelectable: max });
  return exact;
}

