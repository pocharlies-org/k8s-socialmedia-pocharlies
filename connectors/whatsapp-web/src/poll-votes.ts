function secretKey(
  secret: Uint8Array,
  messageId: string,
  creator: string,
  modifier: string,
  useCase: 'Poll Vote' | 'Event Response'
): Buffer {
  const info = Buffer.concat([
    Buffer.from(messageId),
    Buffer.from(creator),
    Buffer.from(modifier),
    Buffer.from(useCase),
    new Uint8Array([1]),
  ]);
  const prk = hmacSign(Buffer.from(secret), new Uint8Array(32), 'sha256');
  return hmacSign(info, prk, 'sha256');
}

/** Exported for event-responses.ts: the same derivation with another use case. */
export function encryptMessageSecret(input: {
  secret: Uint8Array;
  messageId: string;
  creator: string;
  modifier: string;
  useCase: 'Poll Vote' | 'Event Response';
  plaintext: Uint8Array;
  iv?: Uint8Array;
}): { encPayload: Uint8Array; encIv: Uint8Array } {
  const iv = input.iv ?? new Uint8Array(randomBytes(12));
  const key = secretKey(
    input.secret,
    input.messageId,
    input.creator,
    input.modifier,
    input.useCase
  );
  const aad = Buffer.from(`${input.messageId}\u0000${input.modifier}`);
  return { encPayload: aesEncryptGCM(input.plaintext, key, iv, aad), encIv: iv };
}

export interface PollVoteBuild {
  /** Key of the poll creation message (as stored); its id is the poll id. */
  creationKey: WAMessageKey;
  secret: Uint8Array;
  creator: string;
  voter: string;
  /** Exact option names; [] = retract. */
  options: string[];
  senderTimestampMs: number;
  iv?: Uint8Array;
}

/** The pollUpdateMessage of our vote (what WhatsApp's own clients send). */
function buildProductionPollVoteContent(input: PollVoteBuild): WAMessageContent {
  const pollId = String(input.creationKey.id || '');
  if (!pollId) throw new Error('poll creation key without id');
  const plaintext = proto.Message.PollVoteMessage.encode({
    selectedOptions: input.options.map(name => new Uint8Array(sha256(Buffer.from(name)))),
  }).finish();
  const vote = encryptMessageSecret({
    secret: input.secret,
    messageId: pollId,
    creator: input.creator,
    modifier: input.voter,
    useCase: 'Poll Vote',
    plaintext,
    iv: input.iv,
  });
  const group = !!input.creationKey.remoteJid && !!isJidGroup(input.creationKey.remoteJid);
  return {
    pollUpdateMessage: {
      pollCreationMessageKey: {
        remoteJid: input.creationKey.remoteJid,
        fromMe: !!input.creationKey.fromMe,
        id: pollId,
        ...(group ? { participant: input.creator } : {}),
      },
      vote,
      senderTimestampMs: input.senderTimestampMs,
    },
  };
}

export interface DecryptedPollVote {
  /** Hex SHA-256 of each selected option ([] = retracted). */
  hashes: string[];
  creator: string;
  voter: string;
}

/**
 * Decrypt a vote trying every (creator, voter) identity pair. null when none
 * authenticates (wrong secret, unknown identity) — never throws.
 */
export function decryptPollVoteWith(
  vote: proto.Message.IPollEncValue | null | undefined,
  context: { pollId: string; secret: Uint8Array; creators: string[]; voters: string[] }
): DecryptedPollVote | null {
  const encPayload = bytes(vote?.encPayload);
  const encIv = bytes(vote?.encIv);
  if (!encPayload || !encIv || !context.pollId) return null;
  for (const creator of context.creators) {
    for (const voter of context.voters) {
      try {
        const decrypted = decryptPollVote(
          { encPayload, encIv },
          {
            pollCreatorJid: creator,
            pollMsgId: context.pollId,
            pollEncKey: context.secret,
            voterJid: voter,
          }
        );
        return {
          hashes: (decrypted.selectedOptions || []).map(option =>
            Buffer.from(option).toString('hex')
          ),
          creator,
          voter,
        };
      } catch {
        // Not this pair: try the next identity.
      }
    }
  }
  return null;
}

/** ms of a protobuf int64 (number | Long | string); undefined when absent or not positive. */
export function int64Ms(value: unknown): number | undefined {
  if (value === null || value === undefined) return undefined;
  if (typeof value === 'number') return Number.isFinite(value) && value > 0 ? value : undefined;
  if (typeof value === 'bigint') return int64Ms(Number(value));
  if (typeof value === 'string') return int64Ms(Number(value));
  const long = value as { toNumber?: () => number; low?: number; high?: number };
  if (typeof long.toNumber === 'function') return int64Ms(long.toNumber());
  if (typeof long.low === 'number') return int64Ms((long.high || 0) * 2 ** 32 + (long.low >>> 0));
  return undefined;
}

/**
 * WhatsApp poll voting on Baileys 7.0.0-rc13.
 *
 * rc13 ships poll CREATION (`sendMessage({ poll })`) but no vote helper:
 * `generateWAMessageContent` has no `pollUpdateMessage` branch, the automatic
 * inbound-vote decryption in `processMessage` is commented out upstream, and
 * there is no `getPollVotes`-style retrieval. What the library does export is
 * every primitive needed to do it ourselves: `decryptPollVote` (the exact
 * HMAC/AES-GCM scheme WA uses), `aesEncryptGCM`, `hmacSign`, `sha256`,
 * `getKeyAuthor`, `proto`, and `generateWAMessageFromContent`.
 *
 * Vote identity caveat we cannot verify offline: `getKeyAuthor` prefers the
 * `*Alt` (LID) fields, and WA validates a vote hash against the sender
 * identity the signer used. We sign with the same normalized self JID that
 * Baileys' own inbound path (and therefore our aggregation) uses, so our own
 * votes are self-consistent. Cross-device hash acceptance must be confirmed
 * with a live 1:1 vote; see connectors/whatsapp-web README notes.
 */

