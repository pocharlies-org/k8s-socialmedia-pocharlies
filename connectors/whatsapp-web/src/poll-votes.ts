/** This account's own user jids (@s.whatsapp.net / @lid), normalised. */
export interface OwnIdentity {
  pn: string | null;
  lid: string | null;
}

const USER_JID = /^\d+(?::\d+)?@(?:s\.whatsapp\.net|c\.us|lid|hosted|hosted\.lid)$/;

/** A user jid as the crypto uses it (no device, @c.us → @s.whatsapp.net); null otherwise. */
export function cryptoUserJid(jid: string | null | undefined): string | null {
  if (!jid || !USER_JID.test(jid)) return null;
  const normalized = jidNormalizedUser(jid);
  return normalized.endsWith('@s.whatsapp.net') || normalized.endsWith('@lid') ? normalized : null;
}

function unique(jids: Array<string | null | undefined>): string[] {
  const out: string[] = [];
  for (const jid of jids) {
    const user = cryptoUserJid(jid);
    if (user && !out.includes(user)) out.push(user);
  }
  return out;
}

/**
 * Every identity the author of the message with this key may have signed
 * with: ours when fromMe; else the participant (group) or the chat (1:1), as
 * addressed first, then its alternate (PN ↔ LID) when Baileys carried it.
 */
export function keyAuthorCandidates(
  key: WAMessageKey | null | undefined,
  own: OwnIdentity
): string[] {
  if (!key) return [];
  if (key.fromMe) return unique([own.lid, own.pn]);
  const group = !!key.remoteJid && !!isJidGroup(key.remoteJid);
  return group
    ? unique([key.participant, key.participantAlt])
    : unique([key.remoteJid, key.remoteJidAlt]);
}

/**
 * The (creator, voter) pair to sign OUR vote / response with. `lidAddressed`
 * says how the chat addresses people (group addressingMode, or a 1:1 chat
 * with a @lid); it decides our identity for a poll of ours. For someone
 * else's poll the creator is the sender as addressed and we vote with our LID
 * unless that sender is a phone jid (whatsmeow's rule).
 */
export function pollSigningPair(
  creationKey: WAMessageKey,
  own: OwnIdentity,
  lidAddressed: boolean
): { creator: string; voter: string } | null {
  const ownIn = (lid: boolean): string | null => (lid ? own.lid || own.pn : own.pn || own.lid);
  if (creationKey.fromMe) {
    const me = ownIn(lidAddressed);
    return me ? { creator: me, voter: me } : null;
  }
  const group = !!creationKey.remoteJid && !!isJidGroup(creationKey.remoteJid);
  const creator = cryptoUserJid(group ? creationKey.participant : creationKey.remoteJid);
  if (!creator) return null;
  const voter = ownIn(creator.endsWith('@lid'));
  return voter ? { creator, voter } : null;
}

