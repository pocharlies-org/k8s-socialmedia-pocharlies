interface Llamada { metodo: string; url: string; firmada: boolean }

async function montar(opciones: { canalCaido?: boolean; jidPropio?: string } = {}) {
  const llamadas: Llamada[] = [];
  const fakeFetch = (async (input: string | URL, init?: RequestInit) => {
    const url = new URL(String(input));
    const headers = new Headers(init?.headers);
    llamadas.push({ metodo: init?.method ?? 'GET', url: url.pathname + url.search, firmada: !!headers.get('x-connector-signature') });
    if (opciones.canalCaido) return new Response(JSON.stringify({ error: 'Not connected' }), { status: 503 });
    if (url.host === 'wa.test' && url.pathname === '/api/public/history/34600111222%40c.us') {
      return Response.json({ messages: historialWa });
    }
    if (url.host === 'tg.test' && url.pathname === '/api/public/messages/777000111') {
      return Response.json({ messages: mensajesTg });
    }
    if (url.host === 'wa.test' && url.pathname.startsWith('/api/public/history/')) return Response.json({ messages: [] });
    // SC-1500: what the Telegram connector answers today for a peer it cannot resolve.
    if (url.host === 'tg.test' && url.pathname === '/api/public/messages/777000222') {
      return Response.json({ error: 'Error: Telegram API error 400: PEER_ID_INVALID' }, { status: 500 });
    }
    return new Response('{}', { status: 404 });
  }) as typeof fetch;
  const conectores = new ClienteConectores({
    whatsappUrl: 'http://wa.test',
    telegramUrl: 'http://tg.test',
    secreto: 'secreto-compartido-de-prueba',
    fetchImpl: fakeFetch,
  });
  const refs = new IndiceRefs(1000, 86_400_000);
  refs.guardar('3EB0A1B2C3D4E5F60002', '34600111222@c.us');
  refs.guardar('tg:4242', 'tg:777000111');
  const manejar = crearLectura({
    secretos: new Map([[WA.clave_id, WA.secreto], [TG.clave_id, TG.secreto]]),
    conectores,
    jidPropio: async () => opciones.jidPropio ?? JID_PROPIO,
    refs,
    ahoraS: () => AHORA_S,
    logger: pino({ level: 'silent' }),
  });
  const server: Server = createServer((req, res) => {
    void manejar(req, res).then(atendida => {
      if (!atendida) { res.writeHead(418); res.end(); }
    });
  });
  await new Promise<void>(r => server.listen(0, '127.0.0.1', r));
  const port = (server.address() as AddressInfo).port;
  return { llamadas, port, cerrar: () => new Promise<void>(r => server.close(() => r())) };
}

// A raw request: the path goes on the wire exactly as written (`@` and `:` too).
function pedir(port: number, ruta: string, cabeceras: Record<string, string> = {}, metodo = 'GET', cuerpo = ''):
  Promise<{ status: number; json: any }> {
  return new Promise((resolve, reject) => {
    const headers = cuerpo ? { ...cabeceras, 'Content-Length': String(Buffer.byteLength(cuerpo)) } : cabeceras;
    const req = request({ host: '127.0.0.1', port, path: ruta, method: metodo, headers }, res => {
      let datos = '';
      res.on('data', c => (datos += c));
      res.on('end', () => resolve({ status: res.statusCode ?? 0, json: datos ? JSON.parse(datos) : null }));
    });
    req.on('error', reject);
    req.end(cuerpo);
  });
}

function firmado(clave: { clave_id: string; secreto: string }, ruta: string, ts = AHORA_S, metodo = 'GET', cuerpo = '') {
  return {
    'X-Correo-Key-Id': clave.clave_id,
    'X-Correo-Timestamp': String(ts),
    'X-Correo-Signature': firmarV2(clave.secreto, String(ts), metodo, ruta, cuerpo),
  };
}

test('C4: our HMAC V2 gives the same signature as correo-core hmac.py on every vector', () => {
  for (const v of hmac.vectores) {
    assert.equal(firmarV2(v.secreto, v.ts, v.metodo, v.objetivo, v.cuerpo), v.firma, v.objetivo);
  }
});

test('C4: GET /hilos/34600111222@c.us?limite=30 signed by hmac.py verifies over the raw URL', async () => {
  const s = await montar();
  try {
    const r = await pedir(s.port, WA.objetivo, { 'X-Correo-Key-Id': WA.clave_id, 'X-Correo-Timestamp': WA.ts, 'X-Correo-Signature': WA.firma });
    assert.equal(r.status, 200, JSON.stringify(r.json));
    // Oldest to newest; direction from the own JID (the connector says fromMe:false always).
    assert.deepEqual(r.json.mensajes.map((m: any) => [m.ref, m.direccion]), [
      ['3EB0A1B2C3D4E5F60001', 'entrante'],
      ['3EB0A1B2C3D4E5F60002', 'entrante'],
      ['3EB0A1B2C3D4E5F60003', 'saliente'],
    ]);
    const m = r.json.mensajes[0];
    assert.deepEqual(m, {
      ref: '3EB0A1B2C3D4E5F60001',
      hilo_ref: '34600111222@c.us',
      direccion: 'entrante',
      ts: new Date((AHORA_S - 30) * 1000).toISOString().replace(/\.\d{3}Z$/, 'Z'),
      texto: 'Hola, ¿dónde está mi pedido?',
      adjuntos: [],
    });
  } finally {
    await s.cerrar();
  }
});

