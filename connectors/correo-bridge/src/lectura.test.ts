test('C4: no signature, signature of another body, other key, unknown key or out of window → 401', async () => {
  const s = await montar();
  try {
    const ruta = WA.objetivo;
    const casos: Array<[string, Record<string, string>, string]> = [
      ['sin firma', {}, ''],
      ['firma de otro cuerpo', { ...firmado(WA, ruta, AHORA_S, 'GET', '{"otro":1}') }, ''],
      ['firma de otra ruta', { ...firmado(WA, '/hilos/34600111222@c.us?limite=29') }, ''],
      ['firma con la clave de Telegram', { ...firmado({ clave_id: WA.clave_id, secreto: TG.secreto }, ruta) }, ''],
      ['clave desconocida', { ...firmado({ clave_id: 'wa-otro', secreto: WA.secreto }, ruta) }, ''],
      ['fuera de ventana (+61 s)', { ...firmado(WA, ruta, AHORA_S + 61) }, ''],
      ['fuera de ventana (-61 s)', { ...firmado(WA, ruta, AHORA_S - 61) }, ''],
      ['cuerpo que no estaba firmado', { ...firmado(WA, ruta) }, '{"x":1}'],
    ];
    for (const [nombre, cabeceras, cuerpo] of casos) {
      const r = await pedir(s.port, ruta, cabeceras, 'GET', cuerpo);
      assert.equal(r.status, 401, nombre);
      assert.deepEqual(Object.keys(r.json).sort(), ['detalle', 'error']);
      assert.equal(r.json.error, 'no_autenticado', nombre);
    }
    assert.equal(s.llamadas.length, 0, 'nothing reaches a connector without a valid signature');
  } finally {
    await s.cerrar();
  }
});

test('C4: GET /mensajes/{ref}: a known ref is read live, 5000 chars come back as 4096, attachments only as {tipo}', async () => {
  const s = await montar();
  try {
    const ruta = '/mensajes/3EB0A1B2C3D4E5F60002';
    const r = await pedir(s.port, ruta, firmado(WA, ruta));
    assert.equal(r.status, 200, JSON.stringify(r.json));
    assert.equal(r.json.texto.length, 4096);
    assert.deepEqual(r.json.adjuntos, [{ tipo: 'image' }]);
    assert.equal(r.json.hilo_ref, '34600111222@c.us');

    const rt = '/mensajes/tg:4242';
    const t = await pedir(s.port, rt, firmado(TG, rt));
    assert.equal(t.status, 200, JSON.stringify(t.json));
    assert.deepEqual(t.json.adjuntos, [{ tipo: 'photo' }]);
    assert.equal(t.json.texto, '');
    assert.equal(t.json.direccion, 'entrante');
    assert.ok(!JSON.stringify(t.json).includes('privado.jpg'));
    assert.ok(!JSON.stringify(t.json).includes('F1'));
  } finally {
    await s.cerrar();
  }
});

