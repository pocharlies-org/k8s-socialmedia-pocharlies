#!/usr/bin/env node
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '/app/node_modules/playwright/index.mjs');
const publicDir = path.resolve(process.env.UI_SOURCE_DIR || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public'));
const server = createServer(async (request, response) => {
  const name = new URL(request.url, 'http://localhost').pathname;
  const filename = path.resolve(publicDir, `.${name === '/' ? '/index.html' : name}`);
  if (!filename.startsWith(`${publicDir}${path.sep}`)) { response.writeHead(403).end(); return; }
  try {
    const body = await readFile(filename);
    const extension = path.extname(filename);
    response.writeHead(200, {'content-type': {'.html':'text/html', '.js':'text/javascript', '.mjs':'text/javascript', '.css':'text/css', '.svg':'image/svg+xml', '.woff2':'font/woff2'}[extension] || 'application/octet-stream'}).end(body);
  } catch { response.writeHead(404).end(); }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({headless:true, executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH || '/ms-playwright/chromium-1246/chrome-linux64/chrome'});
const page = await browser.newPage();
const chats = {alpha:[{id:'one',name:'Uno'},{id:'two',name:'Dos'}],beta:[{id:'three',name:'Tres'}]};
const messages = {one:[],two:[],three:[]};
const sends = [];
const uploads = [];
const errors = [];
let sessionScope = 'session-a';
page.on('pageerror', error => errors.push(error.message));
await page.route('**/api/**', async route => {
  const request = route.request();
  const url = new URL(request.url());
  const account = url.searchParams.get('account') || 'alpha';
  const chat = url.searchParams.get('chat') || '';
  const json = data => route.fulfill({status:200, contentType:'application/json', body:JSON.stringify(data)});
  if (url.pathname === '/api/accounts') return json({accounts:[{id:'alpha',label:'Alpha'},{id:'beta',label:'Beta'}],sendingEnabled:true,outboxScope:sessionScope});
  if (url.pathname === '/api/models') return json({models:[]});
  if (url.pathname === '/api/chats') return json({chats:chats[account]});
  if (url.pathname === '/api/messages') return json({messages:messages[chat]});
  if (url.pathname === '/api/ai/sessions') return json({sessions:[]});
  if (url.pathname === '/api/send') { sends.push({route, body:request.postDataJSON()}); return; }
  if (url.pathname === '/api/upload') { uploads.push({route, body:request.postDataJSON()}); return; }
  return json({});
});
try {
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await page.locator('.chat-item').first().click();
  await page.locator('#message').fill('primero');
  await page.locator('#message').press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-send-state="sending"]'));
  assert.equal(await page.locator('#message').inputValue(), '');
  assert.equal(await page.locator('#message').isEnabled(), true);
  await page.locator('#message').fill('segundo');
  await page.locator('#message').press('Enter');
  await page.waitForFunction(() => document.querySelectorAll('[data-send-state="sending"]').length === 2);
  assert.equal(sends.length, 2);
  assert.match(sends[0].body.sendToken, /^[0-9a-f-]{36}$/i);
  assert.notEqual(sends[0].body.sendToken, sends[1].body.sendToken, 'independent sends reused a token');
  await sends[1].route.fulfill({status:502,contentType:'application/json',body:JSON.stringify({error:'No confirmado'})});
  await page.waitForFunction(() => document.querySelector('[data-send-state="failed"]'));
  await page.locator('#message').fill('nuevo borrador');
  await page.getByRole('button', {name:'Editar texto'}).click();
  assert.equal(await page.locator('#message').inputValue(), 'nuevo borrador\nsegundo');
  await page.locator('#message').fill('adjunto');
  await page.locator('#attachment').setInputFiles({name:'nota.txt',mimeType:'text/plain',buffer:Buffer.from('contenido')});
  await page.locator('#message').press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-send-state="sending"]'));
  assert.equal(await page.locator('#message').inputValue(), '');
  await page.waitForFunction(() => document.querySelector('#attachment-preview')?.hidden === true);
  await page.waitForFunction(() => document.querySelector('#account option[value="beta"]'));
  await page.locator('#account').evaluate(select => { select.value = 'beta'; select.dispatchEvent(new Event('change', {bubbles:true})); });
  await page.waitForFunction(() => document.querySelector('#account')?.value === 'beta');
  await page.waitForFunction(() => document.querySelector('#chats')?.textContent.includes('Tres'));
  await page.waitForFunction(() => document.querySelector('#messages')?.textContent.includes('Selecciona'));
  await page.waitForFunction(() => document.querySelector('#account')?.value === 'beta');
  await page.waitForTimeout(50);
  assert.equal(uploads.length, 1);
  assert.equal(uploads[0].body.data, Buffer.from('contenido').toString('base64'));
  assert.match(uploads[0].body.sendToken, /^[0-9a-f-]{36}$/i);
  await uploads[0].route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({messageId:'wa-file'})});
  messages.one.push({id:'db-file',waMessageId:'wa-file',text:'adjunto',fromMe:true,timestamp:new Date().toISOString()});
  await page.locator('#account').evaluate(select => { select.value = 'alpha'; select.dispatchEvent(new Event('change', {bubbles:true})); });
  await page.waitForFunction(() => document.querySelector('#chats')?.textContent.includes('Uno'));
  await page.locator('.chat-item').first().click();
  await page.waitForFunction(() => document.querySelectorAll('#messages .message-text').length === 2);
  assert.equal(await page.locator('#messages').getByText('adjunto').count(), 1);
  assert.equal(sends.length, 2, 'failed send must not retry automatically');
  await page.locator('.chat-item').nth(1).click();
  messages.one.push({id:'db-1',waMessageId:'wa-1',text:'primero',fromMe:true,timestamp:new Date().toISOString()});
  await sends[0].route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({messageId:'wa-1'})});
  await page.locator('.chat-item').first().click();
  await page.waitForFunction(() => document.querySelectorAll('#messages .message-text').length === 2);
  assert.equal(await page.locator('#messages').getByText('primero').count(), 1);
  assert.equal(await page.locator('#message').inputValue(), '');
  await page.locator('#message').fill('fallo de archivo');
  await page.locator('#attachment').setInputFiles({name:'fallo.txt',mimeType:'text/plain',buffer:Buffer.from('recuperable')});
  await page.locator('#message').press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-send-state="sending"]'));
  await page.waitForFunction(() => document.querySelectorAll('[data-send-state="sending"]').length === 1);
  await page.waitForTimeout(50);
  assert.equal(uploads.length, 2);
  await uploads[1].route.fulfill({status:502,contentType:'application/json',body:JSON.stringify({error:'No confirmado'})});
  await page.waitForFunction(() => document.querySelector('[data-send-state="failed"]'));
  await page.getByRole('button', {name:'Editar texto'}).click();
  assert.equal(await page.locator('#message').inputValue(), 'fallo de archivo');
  assert.equal(await page.locator('#attachment-preview').isVisible(), true);
  assert.equal(uploads.length, 2, 'failed attachment must not retry automatically');
  await page.locator('#attachment-remove').click();
  await page.locator('#message').fill('igual');
  await page.locator('#message').press('Enter');
  while (sends.length < 3) await new Promise(resolve => setTimeout(resolve, 10));
  await page.locator('#message').fill('igual');
  await page.locator('#message').press('Enter');
  await page.waitForFunction(() => document.querySelectorAll('[data-send-state="sending"]').length === 2);
  assert.equal(sends.length, 4);
  assert.notEqual(sends[2].body.sendToken, sends[3].body.sendToken, 'same text from separate actions reused a token');
  messages.one.push({id:'db-same',waMessageId:'wa-same-2',text:'igual',fromMe:true,timestamp:new Date().toISOString()});
  await sends[3].route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({messageId:'wa-same-2'})});
  await page.waitForFunction(() => document.querySelectorAll('[data-send-state="sending"]').length === 1);
  await sends[2].route.fulfill({status:502,contentType:'application/json',body:JSON.stringify({error:'No confirmado'})});
  await page.waitForFunction(() => document.querySelectorAll('[data-send-state="failed"]').length === 1);
  assert.equal(await page.locator('#messages .message-text').filter({hasText:'igual'}).count(), 2, 'identical messages were reconciled by text');
  await page.reload();
  await page.locator('.chat-item').first().click();
  await page.waitForFunction(() => document.querySelector('[data-send-state="failed"]'));
  assert.equal(await page.locator('#messages .message-text').filter({hasText:'igual'}).count(), 2, 'reload lost unconfirmed text');
  assert.equal(sends.length, 4, 'reload retried an uncertain send without user action');
  await page.getByRole('button', {name:'Reintentar el mismo envío'}).click();
  await page.waitForFunction(() => document.querySelector('[data-send-state="sending"]'));
  assert.equal(sends.length, 5);
  assert.equal(sends[4].body.sendToken, sends[2].body.sendToken, 'manual retry changed the operation token');
  assert.equal(sends[4].body.text, sends[2].body.text);
  await sends[4].route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({messageId:'wa-same-1',deduplicated:true})});
  await page.waitForFunction(() => !document.querySelector('[data-send-state="sending"]'));
  await page.locator('#message').fill('privado');
  await page.locator('#message').press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-send-state="sending"]'));
  sessionScope = 'session-b';
  await page.reload();
  await page.locator('.chat-item').first().click();
  assert.equal(await page.locator('#messages').getByText('privado').count(), 0, 'another session saw the previous session outbox');
  assert.equal(await page.evaluate(() => sessionStorage.getItem('wa-unconfirmed-outbox-v1')), null);
  const input = page.locator('#message');
  await input.fill(Array.from({length:12}, (_, index) => `línea ${index}`).join('\n'));
  const expandedHeight = await input.evaluate(element => element.getBoundingClientRect().height);
  assert.ok(expandedHeight > 100 && expandedHeight <= 240, `composer did not grow within its limit: ${expandedHeight}`);
  await input.fill('confirmación inmediata');
  assert.ok(await input.evaluate(element => element.getBoundingClientRect().height) < expandedHeight, 'composer did not shrink after editing');
  await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-send-state="sending"]'));
  assert.equal(await input.inputValue(), '');
  assert.ok(await input.evaluate(element => element.getBoundingClientRect().height) < expandedHeight, 'composer did not shrink after sending');
  await sends.at(-1).route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({messageId:'wa-immediate'})});
  await page.waitForFunction(() => document.querySelector('[data-send-state="confirmed"]'));
  assert.equal(await page.locator('[data-send-state="confirmed"] .message-send-feedback').count(), 0, 'sending feedback remained after confirmation');
  assert.equal(await page.locator('[data-send-state="confirmed"]').getAttribute('aria-label'), null);
  await page.locator('#account').evaluate(select => { select.value = 'beta'; select.dispatchEvent(new Event('change', {bubbles:true})); });
  await page.waitForFunction(() => document.querySelector('#chats')?.textContent.includes('Tres'));
  await page.locator('.chat-item').first().click();
  await page.locator('#message').fill('mensaje de beta');
  await page.locator('#message').press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-send-state="sending"]'));
  messages.three.push({id:'db-beta',waMessageId:'beta:wa-beta',text:'mensaje de beta',fromMe:true,timestamp:new Date().toISOString()});
  await sends.at(-1).route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({messageId:'wa-beta'})});
  await page.waitForFunction(() => document.querySelectorAll('#messages .message-text').length === 1 && !document.querySelector('[data-send-state]'));
  assert.equal(await page.locator('#messages .message-text').filter({hasText:'mensaje de beta'}).count(), 1, 'account-prefixed provider ID left a duplicate');
  assert.deepEqual(errors, []);
  console.log('Optimistic send browser QA passed');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
